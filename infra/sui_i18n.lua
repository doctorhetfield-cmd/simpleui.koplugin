-- sui_i18n.lua — Simple UI
-- Translation loader.
--
-- Each module exports its own translate() / ngettext() pair, used directly as
-- its local `_` / `N_`. The global gettext module is never replaced or
-- wrapped, so writes made to it by other code always reach the native module.
--
-- Public API:
--   local I18n = require("infra/sui_i18n")
--   local _    = I18n.translate    -- replaces: local _ = require("gettext")
--   local N_   = I18n.ngettext     -- replaces: local N_ = _.ngettext
--   I18n.getLang()                 -- still works
--   I18n.reset()                   -- clears cached translations
--
-- Strings not found in simpleui's .po files fall through to the native
-- gettext, so KOReader's own UI strings continue to work correctly.
--
-- HOW TO ADD A LANGUAGE
--   1. Copy locale/simpleui.pot -> locale/<lang>.po  (e.g. locale/de.po)
--   2. Fill in the msgstr values.
--   3. Done — no code changes needed.

local logger = require("logger")
local util   = require("util")

-- Locate the plugin directory from this file's path.
local _dir = require("infra/sui_paths").getPluginDir()

-- ---------------------------------------------------------------------------
-- .po parser — minimal, handles the subset generated by simpleui.pot
-- ---------------------------------------------------------------------------
-- Evaluates a gettext "Plural-Forms" header (C expression over `n`) with a
-- recursive-descent parser; returns n -> form index, or nil if unparseable.
local function parsePluralExpression(expr)
    expr = expr:match("plural%s*=%s*(.-)%s*;?%s*$") or expr

    local toks, pos = {}, 1
    while pos <= #expr do
        local s = expr:match("^%s+", pos)
        if s then
            pos = pos + #s
        else
            local t = expr:match("^%d+", pos)
                or expr:match("^[=!<>]=", pos)
                or expr:match("^&&", pos) or expr:match("^||", pos)
                or expr:match("^[n%(%)%?:!<>%%%*/%+%-]", pos)
            if not t then return nil end
            toks[#toks + 1] = t
            pos = pos + #t
        end
    end

    local i = 1
    local parseTernary

    -- Left-associative binary level: ops maps token -> function(a, b).
    local function binary(next_level, ops)
        return function()
            local lhs = next_level()
            while lhs and ops[toks[i]] do
                local op = ops[toks[i]]
                i = i + 1
                local rhs = next_level()
                if not rhs then return nil end
                local l = lhs
                lhs = function(n) return op(l(n), rhs(n)) end
            end
            return lhs
        end
    end

    local function parsePrimary()
        local t = toks[i]
        if not t then return nil end
        i = i + 1
        if t == "n" then return function(n) return n end end
        if t:match("^%d+$") then
            local v = tonumber(t)
            return function() return v end
        end
        if t == "(" then
            local e = parseTernary()
            if not e or toks[i] ~= ")" then return nil end
            i = i + 1
            return e
        end
        return nil
    end

    local function parseUnary()
        if toks[i] == "!" then
            i = i + 1
            local e = parseUnary()
            if not e then return nil end
            return function(n) return e(n) == 0 and 1 or 0 end
        end
        return parsePrimary()
    end

    local function b2n(v) return v and 1 or 0 end
    local mul = binary(parseUnary, {
        ["*"] = function(a, b) return a * b end,
        ["/"] = function(a, b) return b ~= 0 and math.floor(a / b) or 0 end,
        ["%"] = function(a, b) return b ~= 0 and a % b or 0 end,
    })
    local add = binary(mul, {
        ["+"] = function(a, b) return a + b end,
        ["-"] = function(a, b) return a - b end,
    })
    local rel = binary(add, {
        ["<"]  = function(a, b) return b2n(a < b) end,
        [">"]  = function(a, b) return b2n(a > b) end,
        ["<="] = function(a, b) return b2n(a <= b) end,
        [">="] = function(a, b) return b2n(a >= b) end,
    })
    local eq = binary(rel, {
        ["=="] = function(a, b) return b2n(a == b) end,
        ["!="] = function(a, b) return b2n(a ~= b) end,
    })
    local land = binary(eq, {
        ["&&"] = function(a, b) return b2n(a ~= 0 and b ~= 0) end,
    })
    local lor = binary(land, {
        ["||"] = function(a, b) return b2n(a ~= 0 or b ~= 0) end,
    })

    -- cond ? a : b, right-associative.
    parseTernary = function()
        local cond = lor()
        if not cond or toks[i] ~= "?" then return cond end
        i = i + 1
        local a = parseTernary()
        if not a or toks[i] ~= ":" then return nil end
        i = i + 1
        local b = parseTernary()
        if not b then return nil end
        return function(n) return cond(n) ~= 0 and a(n) or b(n) end
    end

    local fn = parseTernary()
    if not fn or i <= #toks then return nil end
    return function(n) return fn(math.floor(math.abs(tonumber(n) or 0))) end
end

local function parsePO(path)
    local f = io.open(path, "r")
    if not f then return nil end

    local map        = {}
    local pluralizer = nil
    local entry      = { msgid = nil, msgid_plural = nil, msgstrs = {} }
    local current_field = nil

    local function flush()
        if not entry.msgid then
            entry         = { msgid = nil, msgid_plural = nil, msgstrs = {} }
            current_field = nil
            return
        end

        if entry.msgid == "" then
            local header = entry.msgstrs[0] or ""
            for line in header:gmatch("([^\n]*)\n?") do
                local plural_line = line:match("^Plural%-Forms:%s*(.-)%s*$")
                if plural_line then
                    pluralizer = parsePluralExpression(plural_line)
                    break
                end
            end
        else
            if entry.msgid_plural then
                local trans = {}
                for idx, str in pairs(entry.msgstrs) do
                    if str and str ~= "" then trans[idx] = str end
                end
                if next(trans) then map[entry.msgid] = trans end
            else
                local str = entry.msgstrs[0]
                if str and str ~= "" then map[entry.msgid] = str end
            end
        end

        entry         = { msgid = nil, msgid_plural = nil, msgstrs = {} }
        current_field = nil
    end

    local function unescape(s)
        return s:gsub("\\n", "\n"):gsub("\\t", "\t"):gsub('\\"', '"'):gsub("\\\\", "\\")
    end

    for line in f:lines() do
        local text = util.trim(line)
        if text == "" then
            flush()
        elseif text:match("^#") then
            -- ignore comments
        elseif text:match('^msgid%s+"') then
            flush()
            entry.msgid = unescape(text:match('^msgid%s+"(.*)"') or "")
            current_field = "msgid"
        elseif text:match('^msgid_plural%s+"') then
            entry.msgid_plural = unescape(text:match('^msgid_plural%s+"(.*)"') or "")
            current_field = "msgid_plural"
        elseif text:match('^msgstr%[%d+%]%s+"') then
            local idx = tonumber(text:match('^msgstr%[(%d+)%]%s+"'))
            entry.msgstrs[idx] = unescape(text:match('^msgstr%[%d+%]%s+"(.*)"') or "")
            current_field = "msgstr" .. idx
        elseif text:match('^msgstr%s+"') then
            entry.msgstrs[0] = unescape(text:match('^msgstr%s+"(.*)"') or "")
            current_field = "msgstr0"
        elseif text:match('^"') and current_field then
            local cont = unescape(text:match('^"(.*)"') or "")
            if current_field == "msgid" then
                entry.msgid = entry.msgid .. cont
            elseif current_field == "msgid_plural" then
                entry.msgid_plural = entry.msgid_plural .. cont
            else
                local idx = tonumber(current_field:match("^msgstr(%d+)$"))
                if idx then
                    entry.msgstrs[idx] = (entry.msgstrs[idx] or "") .. cont
                end
            end
        end
    end
    flush()
    f:close()
    return map, pluralizer
end

-- ---------------------------------------------------------------------------
-- Language detection
-- ---------------------------------------------------------------------------
local function detectLang()
    local lang = G_reader_settings and G_reader_settings:readSetting("language")
    if type(lang) == "string" and lang ~= "" then return lang end
    local lc = os.getenv("LANG") or os.getenv("LC_ALL") or os.getenv("LC_MESSAGES") or ""
    lang = lc:match("^([a-zA-Z_]+)")
    return lang or "en"
end

-- ---------------------------------------------------------------------------
-- Load translation table (lazy, cached)
-- ---------------------------------------------------------------------------
local _translations = nil
local _loaded       = false

local function loadTranslations()
    if _loaded then return _translations end
    _loaded = true

    local lang = detectLang()
    if lang == "en" or lang:match("^en_") then return nil end

    local function try(name)
        local path = _dir .. "locale/" .. name .. ".po"
        local entries, pluralizer = parsePO(path)
        if entries and next(entries) then
            local n = 0; for _ in pairs(entries) do n = n + 1 end
            logger.info("simpleui i18n: loaded " .. path .. " — " .. n .. " strings")
            return { entries = entries, plural = pluralizer }
        end
    end

    _translations = try(lang) or (function()
        local prefix = lang:match("^([a-zA-Z]+)")
        if prefix and prefix ~= lang then return try(prefix) end
    end)()

    return _translations
end

-- ---------------------------------------------------------------------------
-- Core translation functions.
--
-- Each simpleui module does:
--   local _  = require("infra/sui_i18n").translate
--   local N_ = require("infra/sui_i18n").ngettext
--
-- Strings absent from simpleui's catalogue fall through to the native
-- KOReader gettext without writing to or wrapping package.loaded["gettext"].
-- ---------------------------------------------------------------------------

local function translate(msgid)
    local t = loadTranslations()
    if t then
        local entry = t.entries[msgid]
        if type(entry) == "string" then
            return entry
        elseif type(entry) == "table" then
            return entry[0] or entry[1] or msgid
        end
    end
    -- Read-only access to native gettext — no writes, no state mutation.
    local ok, gt = pcall(require, "gettext")
    if ok and gt then return gt(msgid) end
    return msgid
end

local function ngettext(msgid, msgid_plural, n)
    local t = loadTranslations()
    if t then
        local entry = t.entries[msgid]
        if type(entry) == "table" then
            local idx = 0
            if t.plural then
                idx = t.plural(n) or 0
            else
                idx = (n == 1) and 0 or 1
            end
            -- Use the nearest lower form when this one is untranslated.
            for i = idx, 0, -1 do
                if entry[i] then return entry[i] end
            end
        elseif type(entry) == "string" and n == 1 then
            return entry
        end
    end
    -- Fall through to native gettext.
    local ok, gt = pcall(require, "gettext")
    if ok and gt then
        if type(gt) == "table" and type(gt.ngettext) == "function" then
            return gt.ngettext(msgid, msgid_plural, n)
        end
        local fallback = (n == 1) and msgid or msgid_plural
        return gt(fallback)
    end
    return (n == 1) and msgid or msgid_plural
end

-- ---------------------------------------------------------------------------
-- reset() — clears cached translations (e.g. after a language change).
-- ---------------------------------------------------------------------------
local function reset()
    _translations = nil
    _loaded       = false
    logger.info("simpleui i18n: translation cache cleared")
end

return {
    translate             = translate,
    ngettext              = ngettext,
    getLang               = detectLang,
    parsePluralExpression = parsePluralExpression,
    reset                 = reset,
}
